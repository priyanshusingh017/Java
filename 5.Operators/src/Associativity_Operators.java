public class Associativity_Operators {
    public static void main(String[] args){

        // precedence of associativity
        int a = 6*5-34/2;
        int b = 60/5-34*2;
        System.out.println(a);
        System.out.println(b);


        int c = 13;
        int d = 1;
        System.out.println((2*c*d)/(2*a));
    }
}
